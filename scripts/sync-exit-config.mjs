/**
 * Sync the executor deployment (addresses + ABIs) into
 * src/panik-core/lib/exit.generated.ts.
 *
 * Usage:  npm run sync:exit-config
 * Source: executor/deploy/onchain-config.json in this repo by default. The
 *         executor now lives here, so the default is the in-repo manifest;
 *         set EXIT_CONFIG_SOURCE to point at a deployment somewhere else
 *         (a checkout of panik-executor-archive, a staging deploy) instead.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_SOURCE = path.resolve(here, "../executor/deploy/onchain-config.json");
const source = process.env.EXIT_CONFIG_SOURCE ?? DEFAULT_SOURCE;
const target = path.resolve(here, "../src/panik-core/lib/exit.generated.ts");

if (!fs.existsSync(source)) {
  const fromEnv = Boolean(process.env.EXIT_CONFIG_SOURCE);
  console.error(
    [
      `exit config source not found: ${source}`,
      "",
      "This script reads onchain-config.json, the deployment manifest written by",
      "`npm run deploy:base-sepolia` in executor/ (addresses + ABIs for the exit",
      "executor, lock checker and adapters).",
      "",
      fromEnv
        ? "EXIT_CONFIG_SOURCE is set, so the default in-repo path was not used. Check it, or unset it to read executor/deploy/onchain-config.json."
        : "Redeploy the executor (cd executor && npm run deploy:base-sepolia), or set EXIT_CONFIG_SOURCE to a manifest elsewhere:",
      fromEnv
        ? ""
        : "  EXIT_CONFIG_SOURCE=/path/to/onchain-config.json npm run sync:exit-config",
    ].join("\n"),
  );
  process.exit(1);
}

const cfg = JSON.parse(fs.readFileSync(source, "utf8"));

const out = `/**
 * GENERATED by scripts/sync-exit-config.mjs - DO NOT EDIT.
 * Source: ${path.basename(source)} (network ${cfg.network}, deployed ${cfg.deployedAt}).
 * Regenerate with: npm run sync:exit-config
 */

export const EXIT_CHAIN_ID = ${cfg.chainId} as const;
export const EXIT_NETWORK = ${JSON.stringify(cfg.network)};
export const EXECUTOR_ADDRESS = ${JSON.stringify(cfg.executor)} as \`0x\${string}\`;
export const LOCK_CHECKER_ADDRESS = ${JSON.stringify(cfg.adapters.lockChecker)} as \`0x\${string}\`;

export const EXIT_ADAPTERS = {
  aave: ${JSON.stringify(cfg.adapters.aaveAdapter)} as \`0x\${string}\`,
  moonwell: ${JSON.stringify(cfg.adapters.moonwellAdapter)} as \`0x\${string}\`,
  compound: ${JSON.stringify(cfg.adapters.compoundAdapter)} as \`0x\${string}\`,
  morpho: ${JSON.stringify(cfg.adapters.morphoAdapter)} as \`0x\${string}\`,
} as const;

export const EXIT_USDC_ADDRESS = ${JSON.stringify(cfg.tokens.usdc)} as \`0x\${string}\`;
export const EXIT_DATA_PROVIDER_ADDRESS = ${JSON.stringify(cfg.config.dataProvider)} as \`0x\${string}\`;
export const EXIT_WETH_ADDRESS = ${JSON.stringify(cfg.config.swapAssets[0] ?? "0x4200000000000000000000000000000000000006")} as \`0x\${string}\`;

export const EXECUTOR_ABI = ${JSON.stringify(cfg.abi.executor, null, 2)} as const;

export const LOCK_CHECKER_ABI = ${JSON.stringify(cfg.abi.lockChecker, null, 2)} as const;
`;

fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)} (chain ${cfg.chainId}, executor ${cfg.executor})`);
